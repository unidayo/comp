func calcScore(gameState *GameState, action [N][]Action, gameConst *GameConst) int {
	valid := true
	score := 0
	turn := 0
	for {
		ended := false
		if len(action[0]) == turn {
			ended = true
		}
		if ended {
			break
		}
		turnAction := [N]Action{}
		for i := 0; i < N; i++ {
			turnAction[i] = action[i][turn]
		}
		valid = gameState.PlayTurn(gameConst, turnAction)
		if !valid {
			break
		}
		turn++
	}
	// fmt.Fprintln(os.Stderr, turn)
	// fmt.Fprintln(os.Stderr, gameState)
	if !valid {
		return -1
	}
	for i := 0; i < N; i++ {
		if gameState.DispatchProgress[i] != 5 {
			return -1
		}
	}
	score = turn
	return score
}

// Stateに対し評価値を返す関数 速度を意識する場合は前回からの差分を検討したほうが良い
func (bs *BeamSearch) Evaluate(beamState *BeamSearchState, gameConst *GameConst) float64 {
	board := [N * N]int{}
	for i := range board {
		board[i] = -1
	}
	remainingProcess := 0
	dForCalc := [N * N]int{}
	boxOccupation := beamState.boxOccupations[len(beamState.boxOccupations)-1]
	for i := range dForCalc {
		dForCalc[i] = -1
	}
	queue := [N * N]int{}
	for bnumber := 0; bnumber < N*N; bnumber++ {
		if beamState.completed&(1<<bnumber) != 0 {
			continue
		}
		popIndex := 0
		pushIndex := 0
		distance := 0
		goal := bnumber/N + N - 1
		queue[pushIndex] = beamState.boxState[bnumber][2]
		dForCalc[beamState.boxState[bnumber][2]] = bnumber
		pushIndex++
		keyIndex := 1
		reachable := false
		for {
			if popIndex == keyIndex {
				distance++
				keyIndex = pushIndex
			}
			if popIndex >= N*N {
				break
			}
			p := queue[popIndex]
			if p == goal {
				reachable = true
				break
			}
			for _, np := range gameConst.dirMap[p] {
				if np == -1 {
					continue
				}
				if dForCalc[np] == bnumber {
					continue
				}
				dForCalc[np] = bnumber
				if boxOccupation&(1<<np) != 0 {
					ignore := false
					for b2 := bnumber / N * N; b2 < bnumber; b2++ {
						if beamState.boxState[b2][2] == np {
							ignore = true
							break
						}
					}
					if !ignore {
						continue
					}
				}
				queue[pushIndex] = np
				pushIndex++
			}
			popIndex++
		}
		if !reachable {
			distance = 30
		}
		remainingProcess += distance + 2

	}
	value := -float64(remainingProcess)
	for i := range beamState.turns {
		value -= float64(beamState.turns[i])
	}
	return value
}


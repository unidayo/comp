func (g *BeamSearchState) AddMove(gameConst *GameConst, craneId int, targetBox int, action Action) {
	if g.turns[craneId] >= g.maxTurn {
		g.Poss = append(g.Poss, (1<<(5*N))-1)
		g.Actions = append(g.Actions, (1<<(5*N) - 1))
		g.boxOccupations = append(g.boxOccupations, g.boxOccupations[len(g.boxOccupations)-1]) // 暫定では直前ターンでの占有状態が継続しているとする
		g.craneOccupations = append(g.craneOccupations, BitData(0))                            // 暫定ではどのクレーンの位置も未定なので占有していないとする
		g.maxTurn++

	}
	pos := g.cranePoss[craneId]
	g.Poss[g.turns[craneId]-g.turnOffset] &= ^(0b11111 << (5 * craneId))
	g.Poss[g.turns[craneId]-g.turnOffset] |= pos << (5 * craneId)

	g.Actions[g.turns[craneId]-g.turnOffset] &= ^(0b11111 << (5 * craneId))
	g.Actions[g.turns[craneId]-g.turnOffset] |= int(action) << (5 * craneId)
	g.Rehash(craneId, g.turns[craneId], action)

	// ターン経過
	g.turns[craneId]++
	g.sumTurn++
	if action >= 0 && action < DIRS {
		g.cranePoss[craneId] = gameConst.dirMap[g.cranePoss[craneId]][action]

	}
	g.boardState[g.cranePoss[craneId]] = maxInt(g.boardState[g.cranePoss[craneId]], g.turns[craneId]+1)
	g.craneOccupations[g.turns[craneId]-g.turnOffset] |= 1 << (g.cranePoss[craneId])
	if action == ACTION_P {
		existNewBox := false
		if g.cranePoss[craneId]%N == 0 {
			if gameConst.InvertBoxes[targetBox][1] != N-1 {
				existNewBox = true
			}
		}
		if !existNewBox {
			for t := g.turns[craneId]; t < g.maxTurn+1; t++ {
				g.boxOccupations[t-g.turnOffset] &= ^(1 << g.cranePoss[craneId])
			}
		}
	}
	if action == ACTION_Q {
		if g.cranePoss[craneId]%N != N-1 {
			g.avoidCount++
			for t := g.turns[craneId]; t < g.maxTurn+1; t++ {
				g.boxOccupations[t-g.turnOffset] |= 1 << g.cranePoss[craneId]
			}
		} else {
			g.completed |= 1 << targetBox
			g.numCompleted++
		}
	}
}


type DirMap [N * N][DIRS]int

func NewDirMap(size int) *DirMap {
	dirs := [4]int{1, N, -1, -N}
	dirMap := DirMap{}
	for i := 0; i < N*N; i++ {
		if i%N >= size {
			dirMap[i] = [4]int{-1, -1, -1, -1}
			continue
		}
		if i/N >= size {
			dirMap[i] = [4]int{-1, -1, -1, -1}
			continue
		}
		for d := 0; d < DIRS; d++ {
			ni := i + dirs[d]
			// 除外の条件
			if i%N == size-1 && d == 0 {
				dirMap[i][d] = -1
			} else if i%N == 0 && d == 2 {
				dirMap[i][d] = -1
			} else if i/N == size-1 && d == 1 {
				dirMap[i][d] = -1
			} else if i/N == 0 && d == 3 {
				dirMap[i][d] = -1
			} else {
				dirMap[i][d] = ni
			}
		}
	}
	return &dirMap
}


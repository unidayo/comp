func (bs *BeamSearch) Run(gameState *BeamSearchState, gameConst *GameConst, order *[N * N]int, allowAvoid *[N * N]bool) *Operation {
	if !bs.calculated {
		// 計算
		bsQueue := NewBeamSearchQueue(bs.width)
		bsQueue.Init()
		cGameState := gameState.Copy(true)
		bsQueue.Push(cGameState)
		for d := 0; d < bs.depth+1; d++ {
			bsQueue.Sort()
			index := 0
			for bsQueue.Len() > 0 {
				nowState := bsQueue.Pop()
				if nowState.maxTurn*N >= (nowState.remainingProcess + nowState.sumTurn + 8) {
					nowState.beamValue += float64(nowState.maxTurn*N - (nowState.remainingProcess + nowState.sumTurn + 8))
					// return
				}
				bs.effectiveStates[d][index] = nowState
				index++
			}
			bs.numEffectiveStates[d] = index

			bsQueue.Init()
			if time.Since(bs.start).Microseconds() > TIME_LIMIT*28/30 {
				bsQueue = NewBeamSearchQueue(300)
			}

			if bs.numEffectiveStates[d] == 0 {
				// あんまり好ましい状態ではないが、探索の完了している状態 (bs.depthの設定を見直したほうがいいかも?)
				// fmt.Fprintln(os.Stderr, "WARN: bs.Depth changed", bs.depth, "->", d-1)
				bs.depth = d - 1
			}
			if d == bs.depth {
				bs.calculated = true
				break
			}
			hashs := map[int64]struct{}{}

			for i := 0; i < bs.numEffectiveStates[d]; i++ {
				nowState := bs.effectiveStates[d][i]

				// 有効手についてloop
				bs.tryPossibleActions(gameConst, nowState, order, allowAvoid, -1000, bsQueue, hashs, i, d)

			}
		}
	}
	// 復元(はじめにどの手を採用すればいいのか)
	index := 0
	// fmt.Fprintln(os.Stderr, bs.effectiveStates[bs.depth][0])
	for d := bs.depth; d > bs.nowDepth+1; d-- {
		index = bs.effectiveStates[d][index].prevState
	}
	bs.nowDepth++ // 次回再び読み込んだ場合はすでに計算済み 次の手を返すようnowDepthを更新
	return nil
}

func calcTurnSub(beamState *BeamSearchState, gameConst *GameConst, t int, craneId int, fromPos int, toPos int, minTurn int, ignoreBox bool, turnlimit int) (int, *[]BitData) {
	l := 0
	reachable := BitData(1 << fromPos)
	reachables := pool2.Get().(*[]BitData)
	*reachables = (*reachables)[:0]
	if minTurn > t+20 {
		return 1000, reachables
	}
	if minTurn > turnlimit {
		return 1000, reachables
	}

	count := 0
	addFromPos := true
	iterator := NewBitIterator(reachable)
	turnlimit = minInt(turnlimit, t+gameConst.distanceMap[fromPos][toPos]+4-1)
	for {
		if t > turnlimit+1 {
			return 1000, reachables
		}
		if turnlimit-t < REACHABLEMAP_LIM {
			reachable &= gameConst.reachableMap[toPos][maxInt(turnlimit-t, 0)]
		}
		if reachable == 0 {
			return 1000, reachables
		}
		*reachables = append(*reachables, reachable)

		if t >= minTurn {
			// 持ち上げ可能か判定
			if reachable&(1<<toPos) != 0 {
				count++
				if count >= 2 {
					t--

					break
				}
			} else {
				count = 0
			}
		}
		nextReachable := BitData(0)
		iterator.Init(reachable)
		for !iterator.IsEmpty() {
			pos := iterator.Next()
			nextReachable |= gameConst.Neighbors[pos]
		}
		if t+1 < beamState.maxTurn+1 {
			if beamState.craneOccupations[t+1-beamState.turnOffset]&(1<<BitData(fromPos)) != 0 {
				addFromPos = false
			}
			nextReachable &= ^beamState.craneOccupations[t+1-beamState.turnOffset]
		}
		if !ignoreBox {
			t2 := minInt(t+1, beamState.maxTurn)
			ok := ^beamState.boxOccupations[t2-beamState.turnOffset]
			if addFromPos {
				ok |= 1 << fromPos
			}
			nextReachable &= ok
		}
		if t < beamState.maxTurn {
			poss := beamState.Poss[t-beamState.turnOffset]
			acts := beamState.Actions[t-beamState.turnOffset]
			for index := 0; index < N; index++ {
				pos := poss & (0b11111)
				poss = poss >> 5
				act := acts & (0b11111)
				acts = acts >> 5
				if pos == 0b11111 {
					continue
				}
				if act >= DIRS {
					continue
				}
				p := pos
				np := gameConst.dirMap[p][act]
				if int(reachable&gameConst.Neighbors[p]) == 1<<np {
					nextReachable &= ^(1 << p)
				}
			}
		}

		reachable = nextReachable
		t++
		l++
	}

	return t, reachables
}

func easyCalcTurn(beamState *BeamSearchState, gameConst *GameConst, t int, craneId int, fromPos int, toPos int, minPTurn int, minQTurn int) (int, int) {
	t += gameConst.distanceMap[beamState.cranePoss[craneId]][fromPos]
	t = maxInt(t, minPTurn)
	t += 1
	t += gameConst.distanceMap[fromPos][toPos]
	t = maxInt(t, minQTurn)
	t += 1
	idealturn := beamState.turns[craneId] + (beamState.cranePoss[craneId]%5 - fromPos%5) + 1 + gameConst.distanceMap[fromPos][toPos] + 1 // +クレーンx-boxx   + boxからゴール
	return t, idealturn
}

func calcRouteSub(bs *BeamSearch, beamState *BeamSearchState, gameConst *GameConst, t int, craneId int, fromPos int, toPos int, minTurn int, ignoreBox bool, reachables *[]BitData) *[]Action {
	startt := t

	a := pool.Get().(*[]Action)
	*a = (*a)[:len(*reachables)-2]
	p := toPos
	d := 0
	for index := len(*reachables) - 2; index > 0; index-- {
		(*a)[index-1] = -2
		if (*reachables)[index-1]&(1<<p) != 0 {
			// 前ターンからこの場所に待機
			(*a)[index-1] = ACTION_WAIT
		} else {
			nextp := -1
			pd := 1

			for _ = range DIR_ORDER {
				// for d, np := range gameConst.dirMap[p] {
				np := gameConst.dirMap[p][d]
				if np == -1 {
					d = (d + pd) % DIRS
					continue
				}
				if (*reachables)[index-1]&(1<<np) != 0 {
					ok := true
					if startt+index-1 < beamState.maxTurn {
						poss := beamState.Poss[startt+index-1-beamState.turnOffset]
						acts := beamState.Actions[startt+index-1-beamState.turnOffset]
						for i := 0; i < N; i++ {
							pos := poss & 0b11111
							poss = poss >> 5
							act := acts & 0b11111
							acts = acts >> 5
							if pos == p && act == d {
								ok = false
								break
							}
						}
					}
					if ok {
						(*a)[index-1] = Action(d ^ 2)
						nextp = np
						break
					}
				}
				d = (d + pd) % DIRS
			}
			p = nextp
		}

	}

	return a
}

func calcTurn(beamState *BeamSearchState, gameConst *GameConst, t int, craneId int, fromPos int, toPos int, minPTurn int, minQTurn int, diff int) (int, int, *[]BitData, *[]BitData) {
	// 衝突なども含めて正確に見積もる
	idealturn := beamState.turns[craneId] + (beamState.cranePoss[craneId]%5 - fromPos%5) + 1 + gameConst.distanceMap[fromPos][toPos] + 1 // +クレーンx-boxx   + boxからゴール
	turnlimit := idealturn + diff - 1 - 1 - (toPos%5 - fromPos%5)
	t, reachables1 := calcTurnSub(beamState, gameConst, t, craneId, beamState.cranePoss[craneId], fromPos, minPTurn, true, turnlimit)
	if t == 1000 {
		return 1000, 0, reachables1, nil
	}
	t += 1
	turnlimit += 1 + (toPos%5 - fromPos%5)
	t, reachables2 := calcTurnSub(beamState, gameConst, t, craneId, fromPos, toPos, minQTurn, craneId == 0, turnlimit)

	if t == 1000 {
		return 1000, 0, reachables1, reachables2
	}
	t += 1

	return t, idealturn, reachables1, reachables2
}
func calcRoute(bs *BeamSearch, beamState *BeamSearchState, gameConst *GameConst, craneId int, targetBox int, fromPos int, toPos int, minPTurn int, minQTurn int, reachables1 *[]BitData, reachables2 *[]BitData) (int, int) {

	// 衝突なども含めて正確に見積もる
	var route *[]Action
	route = calcRouteSub(bs, beamState, gameConst, beamState.turns[craneId], craneId, beamState.cranePoss[craneId], fromPos, minPTurn, true, reachables1)
	for i := range *route {
		beamState.AddMove(gameConst, craneId, targetBox, (*route)[i])
	}
	pool.Put(route)
	beamState.AddMove(gameConst, craneId, targetBox, ACTION_P)
	keyt1 := beamState.turns[craneId]
	route = calcRouteSub(bs, beamState, gameConst, beamState.turns[craneId], craneId, fromPos, toPos, minQTurn, craneId == 0, reachables2)
	for i := range *route {
		beamState.AddMove(gameConst, craneId, targetBox, (*route)[i])
	}
	pool.Put(route)
	beamState.AddMove(gameConst, craneId, targetBox, ACTION_Q)

	keyt2 := beamState.turns[craneId]
	beamState.remainingProcess -= gameConst.distanceMap[fromPos][(targetBox/N)*N+N-1]
	beamState.remainingProcess -= toPos%N - fromPos%N
	beamState.remainingProcess += gameConst.distanceMap[toPos][(targetBox/N)*N+N-1]
	if toPos%N == N-1 {
		beamState.remainingProcess -= 2
	}
	return keyt1, keyt2
}

func (bs *BeamSearch) tryPossibleActions(gameConst *GameConst, beamState *BeamSearchState, order *[N * N]int, allowAvoid *[N * N]bool, threshold int, bsQueue *BeamSearchQueue, hashs map[int64]struct{}, prevIndex int, d int) {

	doCopy := false
	cNowState := bsPool.Get().(*BeamSearchState)
	m := 0.0001

	easyJudge := func(craneId int, fromPos int, toPos int, minPTurn int, minQTurn int) int {
		if minPTurn == 1000 || minQTurn == 1000 {
			return -1000
		}
		t, idealturn := easyCalcTurn(beamState, gameConst, beamState.turns[craneId], craneId, fromPos, toPos, minPTurn, minQTurn)
		value := int(beamState.beamValue-0.1) + idealturn - t - int(bsQueue.boarder-0.1)
		return value

	}

	tryAction := func(action *Operation, value float64, reachables1 *[]BitData, reachables2 *[]BitData) {

		if doCopy {
			cNowState = beamState.Copy(true)
		} else {
			cNowState.Load(beamState, true)
		}
		cNowState.ApplyAction(bs, gameConst, order, allowAvoid, action, reachables1, reachables2)
		if cNowState.maxTurn >= bs.bestTurn {
			return
		}
		cNowState.prevState = prevIndex
		cNowState.beamValue = value
		if cNowState.maxTurn*N >= (cNowState.remainingProcess + cNowState.sumTurn + 8) {
			cNowState.beamValue -= float64(cNowState.maxTurn*N - (cNowState.remainingProcess + cNowState.sumTurn + 8))
			// return
		}
		if _, exist := hashs[cNowState.Hash]; !exist {
			if cNowState.completed == (1<<(N*N))-1 {
				if bs.bestTurn > cNowState.maxTurn {
					bs.bestTurn = cNowState.maxTurn
					bs.best = cNowState
					bs.bestDepth = d + 1
					doCopy = true
				}
			} else {
				doCopy = bsQueue.Push(cNowState)
				m *= 0.8
				hashs[cNowState.Hash] = struct{}{}
			}
		}
	}
	var reachables1, reachables2 *[]BitData
	for craneId := 0; craneId < N; craneId++ {
		if beamState.numCompleted > 18 {
			if beamState.turns[craneId] > beamState.nowTurn+5 {
				continue
			}
		} else {
			if beamState.turns[craneId] > beamState.nowTurn+0 {
				continue
			}
		}
		// for bnumber := 0; bnumber < N*N; bnumber++ {
		for addi := 0; addi < beamState.orderIndex+25 && addi < N*N; addi++ {
			threshold2 := -INF
			bnumber := order[addi]
			minPTurn := 1000
			if beamState.boxState[bnumber][0] != -1 {
				minPTurn = beamState.boxState[bnumber][0]
			}
			fromPos := beamState.boxState[bnumber][2]
			for l := 0; l < 1; l++ {
				toPos := (bnumber/5)*N + N - 1
				minQTurn := 1000
				if beamState.boxState[bnumber][1] != -1 {
					minQTurn = beamState.boxState[bnumber][1]
				}

				// 移動距離を加算
				diff := easyJudge(craneId, fromPos, toPos, minPTurn, minQTurn)
				if diff < 0 {
					continue
				}
				if reachables1 != nil {
					pool2.Put(reachables1)
				}
				if reachables2 != nil {
					pool2.Put(reachables2)
				}
				var t, idealturn int
				t, idealturn, reachables1, reachables2 = calcTurn(beamState, gameConst, beamState.turns[craneId], craneId, fromPos, toPos, minPTurn, minQTurn, diff)
				if t == 1000 {
					continue
				}
				if t >= bs.bestTurn {
					continue
				}

				value2 := idealturn - t
				threshold2 = value2
				// value := idealturn - t - turns[craneId]
				if value2 >= threshold {
					action := &Operation{CraneId: craneId, BoxId: bnumber, FromPos: fromPos, ToPos: toPos}
					value := float64(int(beamState.beamValue - 0.1))
					value += float64(value2)
					value += gameConst.Random.Float64() * m
					// value += bs.EvaluateDiff(beamState, action, gameConst)
					if !bsQueue.Promising(value) {
						// 可能性がないのでcontinue
						continue
					}
					tryAction(action, value, reachables1, reachables2)
				}
			}
			for l := 0; l < 1; l++ {
				// 退避候補を全列挙
				if threshold2 != -INF {
					continue
				}
				/*if !allowAvoid[bnumber] {
					continue
				}*/
				fPos := beamState.boxState[bnumber][2]
				if fPos%N != 0 {
					// 一度退避済みであるので、再退避は許さない
					continue
				}
				tPos := (bnumber/N)*N + N - 1
				fromIndex := fPos / N
				toIndex := tPos / N
				if fromIndex > toIndex {
					toIndex, fromIndex = fromIndex, toIndex
				}
				if fromIndex == toIndex {
					fromIndex = maxInt(fromIndex-1, 0)
					toIndex = minInt(toIndex+1, N-1)
				}
				for r := fromIndex; r <= toIndex; r++ {
					count := 0
					for c := 3; c >= 1; c-- {
						if count >= 1 && c == 1 {
							continue
						}
						toPos := r*N + c
						minQTurn := beamState.boardState[toPos]
						plus := 0
						plus -= 1 + /*beamState.avoidCount +*/ 0
						if beamState.numCompleted < 10 && (toPos == N*bs.forbiddenLane+1 || toPos == N*bs.forbiddenLane+2 || toPos == N*bs.forbiddenLane+3) {
							plus -= 100
						}
						if !allowAvoid[bnumber] {
							plus -= 2
						}
						diff := easyJudge(craneId, fromPos, toPos, minPTurn, minQTurn)
						if diff >= 0 {
							count++
						}
						diff += plus
						if diff < 0 {

							continue
						}

						// 移動距離を加算

						if reachables1 != nil {
							pool2.Put(reachables1)
						}
						if reachables2 != nil {
							pool2.Put(reachables2)
						}
						var t, idealturn int
						t, idealturn, reachables1, reachables2 = calcTurn(beamState, gameConst, beamState.turns[craneId], craneId, fromPos, toPos, minPTurn, minQTurn, diff)
						if t == 1000 {
							continue
						}

						value2 := (idealturn + plus) - t
						// value := idealturn - t - turns[craneId]
						if value2 >= threshold && value2 >= threshold2 {
							action := &Operation{CraneId: craneId, BoxId: bnumber, FromPos: fromPos, ToPos: toPos}
							value := float64(int(beamState.beamValue - 0.1))
							value += float64(value2)
							value += gameConst.Random.Float64() * m
							// value += bs.EvaluateDiff(beamState, action, gameConst)
							if !bsQueue.Promising(value) {
								// 可能性がないのでcontinue
								continue
							}
							tryAction(action, value, reachables1, reachables2)
						}
					}
				}
			}
		}

	}
	if !doCopy {
		bsPool.Put(cNowState)
	}

}

// 連続して追加->連続してdeleteminの場合のみ効果のあるPriorityQueue
type BeamSearchQueue struct {
	items     []*BeamSearchState
	popIndex  int
	pushIndex int
	width     int
	sorted    bool

	boarder float64
}

func NewBeamSearchQueue(width int) *BeamSearchQueue {
	q := BeamSearchQueue{}
	q.items = make([]*BeamSearchState, 2*width)
	q.popIndex = 0
	q.pushIndex = 0
	q.boarder = -INF
	q.width = width
	return &q
}

func (q *BeamSearchQueue) Init() {
	q.popIndex = 0
	q.pushIndex = 0
	q.width = len(q.items) / 2
	q.boarder = -INF
	q.sorted = false
}

func (q *BeamSearchQueue) Pop() *BeamSearchState {
	ret := q.items[q.popIndex]
	q.popIndex++
	return ret
}

func (q *BeamSearchQueue) Push(item *BeamSearchState) bool {
	pushed := false
	if q.pushIndex >= len(q.items) {
		q.Sort()
	}
	if q.boarder > item.beamValue {
		// この段階で棄却
		return pushed
	}
	pushed = true
	q.sorted = false
	q.items[q.pushIndex] = item
	q.pushIndex++
	return pushed
}

func (q *BeamSearchQueue) Sort() {
	sort.Slice(q.items[:q.pushIndex], func(i, j int) bool { return q.items[i].beamValue > q.items[j].beamValue })
	if q.pushIndex > q.width {
		// 上位width分以外は捨てる
		for i := q.width; i < q.pushIndex; i++ {
			bsPool.Put(q.items[i])
		}
		q.pushIndex = q.width
		q.boarder = q.items[q.width-1].beamValue
	}
	q.sorted = true
}

func (q *BeamSearchQueue) Promising(v float64) bool {
	return q.boarder <= v
}

func (q *BeamSearchQueue) Len() int {
	// 正しくはこれだが、安全性を無視するなら二つ目のほうが高速
	m := minInt(q.width, q.pushIndex)
	l := maxInt(m-q.popIndex, 0)
	// l := q.pushIndex - q.popIndex
	return l
}


    def append(self, a):
        if (not self.ans) and a[0] == 4:
            # 最序盤の盤面操作は回数が無駄になるので初期盤面の方を修正
            i, j, ii, jj = a[1:]
            if i == ii:
                assert abs(j - jj) == 1
                j = min(j, jj)
                self.initial_wall_horizontal[i][j] ^= 1
            elif j == jj:
                assert abs(i - ii) == 1
                i = min(i, ii)
                self.initial_wall_vertical[i][j] ^= 1
            else:
                assert 0
        else:
            if a[0] == 1:
                self.added_count += 1
            self.ans.append(a)


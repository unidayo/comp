class RatioFinder():
    # (u, uu) の組を探す
    def __init__(self):
        self.pre_calc_I = {}
        self.pre_calc_uuu = {}
        for s in range(3, 101):
            S = set()
            LLUUU = []
            for u in range(1, s):
                for uu in range(1, u):
                    alpha = (u * (s - u + uu)) / (uu * s)
                    if alpha in S:
                        continue
                    S.add(alpha)
                    LLUUU.append((alpha, (u, uu)))
            LLUUU.sort(key = lambda x: x[0])
            I = [alpha for alpha, uuu in LLUUU]
            UUU = [uuu for _, uuu in LLUUU]
            self.pre_calc_I[s] = I
            self.pre_calc_uuu[s] = UUU
    
    def find(self, s, ra):
        if ra < 1.0:
            return None
        if s not in self.pre_calc_I:
            return None
        I, uuu = self.pre_calc_I[s], self.pre_calc_uuu[s]
        i = bisect_left(I, ra)
        if i == 0:
            return I[0], uuu[0]
        if i == len(I):
            return I[-1], uuu[-1]
        if I[i] + I[i-1] > ra * 2:
            i -= 1
        return I[i], uuu[i]
class QuadrupleFinder():
    def __init__(self):
        nu_max = 15
        de_max = 20
        S_nu = set()
        L_nu = []
        for nu_sum in range(2, nu_max * 2 + 1):
            for nu1 in range(1, nu_sum // 2 + 1):
                nu2 = nu_sum - nu1
                assert 1 <= nu1 <= nu2
                nu_prod = nu1 * nu2
                if nu_prod in S_nu:
                    continue
                S_nu.add(nu_prod)
                nunu = nu1 * 100 + nu2
                L_nu.append((nu_prod, nunu))
        S_de = set()
        L_de = []
        for de_sum in range(4, de_max * 2 + 1):
            for de1 in range(2, de_sum // 2 + 1):
                de2 = de_sum - de1
                assert 2 <= de1 <= de2
                de_prod = de1 * de2
                if de_prod in S_de:
                    continue
                S_de.add(de_prod)
                dede = de1 * 100 + de2
                L_de.append((de_prod, dede))
        S = set()
        IL = []
        for nu_prod, nunu in L_nu:
            for de_prod, dede in L_de:
                x = nu_prod / de_prod
                if x in S:
                    continue
                S.add(x)
                key = nunu * 10000 + dede
                nu1, nu2 = nunu // 100, nunu % 100
                de1, de2 = dede // 100, dede % 100
                if nu1 >= de2 or nu1 >= de1 or nu2 >= de2:
                    continue
                IL.append((x, key))
        
        IL.sort(key = lambda x: x[0])
        self.I = [i for i, l in IL]
        self.L = [l for i, l in IL]
        
        self.S_nu = S_nu
        self.L_nu = L_nu
        self.S_de = S_de
        self.L_de = L_de
    
    def find(self, x):
        b = bisect_left(self.I, x)
        if b >= len(self.I):
            return self.L[b-1]
        if b <= 0:
            return self.L[0]
        if self.I[b] + self.I[b-1] > x * 2:
            b -= 1
        return self.L[b]
    

def calc_board_infos_by_board_input(L):
    N = 20
    assert len(L) == N
    for a in L:
        assert len(a) == N
    initial_wall_vertical = [[1] * N for _ in range(N - 1)]
    initial_wall_horizontal = [[1] * (N - 1) for _ in range(N)]
    central_square = []
    board = [[None] * N for _ in range(N)]
    ma = -1
    for i in range(N):
        for j in range(N):
            a = L[i][j]
            if a < 0:
                continue
            if a == 0:
                central_square.append((i, j))
            board[i][j] = a // 100 - 1
            ma = max(ma, board[i][j])
    K = ma + 1
    # print("K =", K)
    central_connection = [None] * K
    board_occupy = []
    for k in range(K):
        mis = [9999999] * K
        for ci, cj in central_square:
            for di, dj in ((-1, 0), (0, 1), (1, 0), (0, -1)):
                i, j = ci + di, cj + dj
                if not 0 <= i < N and 0 <= j < N:
                    continue
                a = board[i][j]
                if a is None:
                    continue
                if 1:
                    ss = L[i][j]
                    if ss < mis[a]:
                        mis[a] = ss
                        central_connection[a] = (ci, cj)
                    continue
                if central_connection[a] is None:
                    central_connection[a] = (ci, cj)
                else:
                    cci, ccj = central_connection[a]
                    if L[i][j] < L[cci][ccj]:
                        central_connection[a] = (ci, cj)
    for k in range(K):
        i, j = central_connection[k]
        path = []
        S = set()
        while 1:
            mi = 10 ** 9
            mi_ij = None
            for di, dj in ((-1, 0), (0, 1), (1, 0), (0, -1)):
                ni, nj = i + di, j + dj
                if not (0 <= ni < N and 0 <= nj < N):
                    continue
                if board[ni][nj] == k:
                    if (ni, nj) in S:
                        continue
                    s = L[ni][nj]
                    if s < mi:
                        mi = s
                        mi_ij = (ni, nj)
            if mi_ij is None:
                break
            i, j = mi_ij
            S.add(mi_ij)
            path.append((i, j))
        board_occupy.append(path[::-1])
    for k in range(K):
        bs = board_occupy[k]
        for (i, j), (ni, nj) in zip(bs, bs[1:]):
            if i == ni:
                initial_wall_horizontal[i][min(j, nj)] = 0
            elif j == nj:
                initial_wall_vertical[min(i, ni)][j] = 0
            else:
                assert 0
    for k in range(K):
        i, j = board_occupy[k][-1]
        ci, cj = central_connection[k]
        if i == ci:
            initial_wall_horizontal[i][min(j, cj)] = 0
        elif j == cj:
            initial_wall_vertical[min(i, ci)][j] = 0
        else:
            assert 0
    for i, j in central_square:
        for ni, nj in central_square:
            if abs(i - ni) + abs(j - nj) == 1:
                if i == ni:
                    initial_wall_horizontal[i][min(j, nj)] = 0
                elif j == nj:
                    initial_wall_vertical[min(i, ni)][j] = 0
                
        
    return initial_wall_horizontal, initial_wall_vertical, central_square, central_connection, board_occupy, board



    def calc_block(self):
        class Block():
            def __init__(self, data, cells):
                self.data = data
                self.cells = cells
                self.size = len(cells)
                self.current_amount = 0.0
                self.current_color = (0.0, 0.0, 0.0)

            def update_initial_walls(self, initial_wall_horizontal, initial_wall_vertical):
                for i, j in self.cells:
                    for di, dj in ((0, 1), (1, 0), (0, -1), (-1, 0)):
                        ni, nj = i + di, j + dj
                        if not (0 <= ni < self.data.N and 0 <= nj < self.data.N):
                            continue
                        if (ni, nj) in self.cells:
                            continue
                        if i == ni:
                            mij = min(j, nj)
                            initial_wall_horizontal[i][mij] = 1
                        if j == nj:
                            mii = min(i, ni)
                            initial_wall_vertical[mii][j] = 1

            def __len__(self):
                return self.size

            def diff(self, c_target):
                err = sqrt((self.current_color[0] - c_target[0]) ** 2 +
                           (self.current_color[1] - c_target[1]) ** 2 +
                           (self.current_color[2] - c_target[2]) ** 2
                           )
                return err

            def add_simulate(self, c_in, c_target):
                err = sqrt(((self.current_color[0] * self.current_amount + c_in[0]) / (self.current_amount + 1) -
                            c_target[0]) ** 2 +
                           ((self.current_color[1] * self.current_amount + c_in[1]) / (self.current_amount + 1) -
                            c_target[1]) ** 2 +
                           ((self.current_color[2] * self.current_amount + c_in[2]) / (self.current_amount + 1) -
                            c_target[2]) ** 2)
                return err

            def add_partial_simulate(self, c_in, c_target, use_size):
                # assert use_size >= self.current_amount + 1 - 0.1 ** 7, (use_size, self.current_amount)
                r = use_size / self.size
                err = sqrt(((self.current_color[0] * self.current_amount * r + c_in[0]) / (
                            self.current_amount * r + 1) - c_target[0]) ** 2 +
                           ((self.current_color[1] * self.current_amount * r + c_in[1]) / (
                                       self.current_amount * r + 1) - c_target[1]) ** 2 +
                           ((self.current_color[2] * self.current_amount * r + c_in[2]) / (
                                       self.current_amount * r + 1) - c_target[2]) ** 2)
                return err

            def toggle_separation(self, x):
                # x の位置でセパレート
                assert x >= 2
                i, j = self.cells[x - 1]
                assert x < len(self.cells), (x, len(self.cells))
                ii, jj = self.cells[x]
                return (4, i, j, ii, jj)

            def add_partial_and_pick(self, k, use_size):
                r = use_size / self.size
                a = self.current_amount
                rr1 = (a * r + 1 - r) / (a * r + 1)  # 元のやつの残る量の割合
                rr2 = r / (a * r + 1)  # 入ってきたやつの残る量の割合
                oc = self.data.own_colors[k]
                self.current_color = ((self.current_color[0] * rr1 + oc[0] * rr2),
                                      (self.current_color[1] * rr1 + oc[1] * rr2),
                                      (self.current_color[2] * rr1 + oc[2] * rr2))
                ret = []
                ret.append(self.toggle_separation(use_size))
                i, j = self.cells[0]
                ret.append((1, i, j, k))
                ret.append((2, i, j))
                ret.append(self.toggle_separation(use_size))
                return ret

            def add(self, k):
                oc = self.data.own_colors[k]
                self.current_color = ((self.current_color[0] * self.current_amount + oc[0]) / (self.current_amount + 1),
                                      (self.current_color[1] * self.current_amount + oc[1]) / (self.current_amount + 1),
                                      (self.current_color[2] * self.current_amount + oc[2]) / (self.current_amount + 1))
                self.current_amount += 1.0
                i, j = self.cells[0]
                return (1, i, j, k)

            def pick(self):
                if 0:
                    self.current_color = (self.current_color[0] * (self.current_amount - 1) / self.current_amount,
                                          self.current_color[1] * (self.current_amount - 1) / self.current_amount,
                                          self.current_color[2] * (self.current_amount - 1) / self.current_amount
                                          )
                self.current_amount -= 1.0
                i, j = self.cells[0]
                return (2, i, j)

            def __bool__(self):
                return self.current_amount >= 0.0001

        initial_wall_horizontal = [[0] * (self.N - 1) for _ in range(self.N)]
        initial_wall_vertical = [[0] * self.N for _ in range(self.N - 1)]
        blocks = [Block(self, [(i, j * 10 + k) for k in range(10)]) for i in range(self.N) for j in range(2)]
        # blocks = [Block(self, [(i, j) for j in range(20)]) for i in range(self.N)]

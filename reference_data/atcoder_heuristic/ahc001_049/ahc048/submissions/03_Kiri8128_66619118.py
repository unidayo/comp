    def calc_greedy(self):
        answer = Answer(self)
        answer.type = "greedy"
        for tc in self.target_colors:
            best_cost = float('inf')
            best_pattern = None
            for a, oc in enumerate(self.own_colors):
                err = sqrt((tc[0] - oc[0]) ** 2 + (tc[1] - oc[1]) ** 2 + (tc[2] - oc[2]) ** 2)

        class Loop():
            def __init__(self):
                self.cells = []
                for k in range(10):
                    i = k * 2
                    for j in range(1, 20 if k else 19):
                        self.cells.append((i, j))
                    i += 1
                    for j in range(1, 20 if k else 19)[::-1]:
                        self.cells.append((i, j))
                for i in range(20)[::-1]:
                    self.cells.append((i, 0))
                
                self.wall_status = [0] * len(self) # 閉じたら1
            
            def __len__(self):
                return len(self.cells)
            
            def set_initial_walls(self, initial_wall_horizontal, initial_wall_vertical):
                for idx in range(len(self.cells)):
                    i, j = self.cells[idx]
                    ii, jj = self.cells[idx-1]
                    if i == ii:
                        assert abs(j - jj) == 1
                        initial_wall_horizontal[i][min(j, jj)] = 0
                    elif j == jj:
                        assert abs(i - ii) == 1
                        initial_wall_vertical[min(i, ii)][j] = 0
                    else:
                        assert 0
            def wall_is_closed(self, idx):
                assert idx <= len(self.wall_status), (idx, len(self.wall_status))
                return self.wall_status[idx % len(self.wall_status)] == 1
            def set_wall(self, idx):
                assert 0 <= idx <= len(self.wall_status), (idx, len(self.wall_status))
                idx %= len(self.wall_status)
                if self.wall_status[idx] == 1:
                    return None
                i, j = self.cells[idx]
                ii, jj = self.cells[idx-1]
                self.wall_status[idx] = 1
                return (4, i, j, ii, jj)
            def remove_wall(self, idx):
                if self.wall_status[idx] == 0:
                    return None
                i, j = self.cells[idx]
                ii, jj = self.cells[idx-1]
                self.wall_status[idx] = 0
                return (4, i, j, ii, jj)
            def toggle_wall(self, idx):
                i, j = self.cells[idx]
                ii, jj = self.cells[idx-1]
                self.wall_status[idx] ^= 1
                return (4, i, j, ii, jj)
            
        
        class Block():
            def __init__(self, data, loop, l_id, r_id, amount=0.0, color_amount=(0.0, 0.0, 0.0)):
                self.data = data
                self.loop = loop
                
                # Loop 内でのセルのIDの範囲 [l, r)
                self.l_id = l_id
                self.r_id = r_id
                
                self.amount = amount
                self.color_amount = color_amount # 色ではなく色の成分×量で持つ
            def __len__(self):
                return self.r_id - self.l_id
            def __str__(self):
                return f"Block({(self.l_id, self.r_id)}, {self.amount}, {self.color_amount}, {self.color_amount[0] / self.amount if self.amount else 0.0, self.color_amount[1] / self.amount if self.amount else 0.0, self.color_amount[2] / self.amount if self.amount else 0.0}"
            def add(self, k):
                oc = self.data.own_colors[k]
                self.amount += 1.0
                self.color_amount = (self.color_amount[0] + oc[0],
                                     self.color_amount[1] + oc[1],
                                     self.color_amount[2] + oc[2])
                i, j = loop.cells[self.l_id]
                return (1, i, j, k)
            def remove_section(self, l, r):
                # [l, r) と重なる部分を除く
                if l <= self.l_id and self.r_id <= r:
                    return []
                elif r <= self.l_id or self.r_id <= l:
                    return [self]
                elif self.l_id < l < r < self.r_id:
                    l1, r1 = self.l_id, l
                    l2, r2 = r, self.r_id
                    ret = []
                    co = (self.color_amount[0] / self.amount,
                          self.color_amount[1] / self.amount,
                          self.color_amount[2] / self.amount,
                         )
                    for ll, rr in ((l1, r1), (l2, r2)):
                        amt = self.amount * (rr - ll) / (self.r_id - self.l_id)
                        col_amt = (co[0] * amt, co[1] * amt, co[2] * amt)
                        new_block = Block(self.data, self.loop, ll, rr, amt, col_amt)
                        ret.append(new_block)
                    return ret
                elif self.l_id < l < self.r_id <= r:
                    ll, rr = self.l_id, l
                    ra = (rr - ll) / (self.r_id - self.l_id)
                    self.amount *= ra
                    self.color_amount = (self.color_amount[0] * ra,
                                         self.color_amount[1] * ra,
                                         self.color_amount[2] * ra
                                        )
                    self.l_id = ll
                    self.r_id = rr
                    return [self]
                elif l <= self.l_id < r < self.r_id:
                    ll, rr = r, self.r_id
                    ra = (rr - ll) / (self.r_id - self.l_id)
                    self.amount *= ra
                    self.color_amount = (self.color_amount[0] * ra,
                                         self.color_amount[1] * ra,
                                         self.color_amount[2] * ra
                                        )
                    self.l_id = ll
                    self.r_id = rr
                    return [self]
                else:
                    assert 0
                
        

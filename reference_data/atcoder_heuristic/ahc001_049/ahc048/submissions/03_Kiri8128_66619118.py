def popcount(x):
    x -= (x >> 1) & 0x5555
    x = (x & 0x3333) + ((x >> 2) & 0x3333)
    x = (x + (x >> 4)) & 0x0f0f
    x += x >> 8
    return x & 0x1f


def calc_ratio(tc, oc1, oc2, oc3, oc4):
    # Solve for w1,w2,w3 in 3x3 and w4 = 1 - (w1+w2+w3)
    # (oc1-oc4)*w1 + (oc2-oc4)*w2 + (oc3-oc4)*w3 = tc - oc4
    # Build vectors
    v1 = (oc1[0] - oc4[0], oc1[1] - oc4[1], oc1[2] - oc4[2])
    v2 = (oc2[0] - oc4[0], oc2[1] - oc4[1], oc2[2] - oc4[2])
    v3 = (oc3[0] - oc4[0], oc3[1] - oc4[1], oc3[2] - oc4[2])
    target = (tc[0] - oc4[0], tc[1] - oc4[1], tc[2] - oc4[2])

    # triple scalar
    def dot(a, b):
        return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]

    def cross(a, b):
        return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])

    det = dot(v1, cross(v2, v3))
    if abs(det) < 1e-12:
        return None
    w1 = dot(target, cross(v2, v3)) / det
    w2 = dot(v1, cross(target, v3)) / det
    w3 = dot(v1, cross(v2, target)) / det
    w4 = 1 - (w1 + w2 + w3)
    # check non-negative within tolerance
    ws = (w1, w2, w3, w4)
    if all(w >= -0.0001 for w in ws):
        return [max(0.0, w) for w in ws]
    if DEBUG:
        if abs(tc[0] - 0.4266) < 0.000001:
            print("ws =", ws)
    return None


def calc_sep_wall(t, cnt):
    # Determine wall between cell(cnt-1) and cell(cnt) along the snake in quadrant t
    def cell_coords(t, k):
        # quadrant size 10x10, each snake of length 100
        g = k // 10
        pos = k % 10
        # row calculation
        if t == 0:
            base_row, dr = 9, -1
        elif t == 1:
            base_row, dr = 10, 1
        elif t == 2:
            base_row, dr = 10, 1
        else:  # t == 3
            base_row, dr = 9, -1
        row = base_row + dr * g
        # col calculation
        if t in (0, 1):  # left quadrants
            base_col = 9
            if g % 2 == 0:
                col = base_col - pos
            else:
                col = pos
        else:  # right quadrants (2,3)
            base_col = 10
            if g % 2 == 0:
                col = base_col + pos
            else:
                col = base_col + (9 - pos)
        return row, col

    # get adjacent cells
    k1, k2 = cnt - 1, cnt
    r1, c1 = cell_coords(t, k1)
    r2, c2 = cell_coords(t, k2)
    # return wall as between cell(cnt) and cell(cnt-1)
    return (r2, c2, r1, c1)



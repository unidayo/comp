	vector<vector<pii>> buildPathsWithCurrentEstimation() {
		int newExpectedCost = 0;

		int numV = w + k;
		uf.init(numV);
		repw(i) {
			uf.unite(0, i);
		}

		dijks.clear();
		rep0(i, numV) {
			dijks.emplace_back(mesh, est, i, totalDamage, prevPaths);
		}
		priority_queue<pii, vector<pii>, greater<pii>> q;
		rep0(i, numV) {
			rep0(j, i) {
				int dist = dijks[i].dists[j];
				if (dist < INF) {
					q.emplace(dist, i << 16 | j);
				}
			}
		}

		set<pii> usedEdges;
		vector<vector<pii>> paths;

		auto& vs = mesh.vs;
		bool done = true;
		while (!q.empty()) {
			pii top = q.top();
			q.pop();
			int dist = top.first;
			int i = top.second >> 16;
			int j = top.second & 0xffff;
			if (uf.same(i, j))
				continue;
			Dijkstra dijk(mesh, est, i, totalDamage, prevPaths, usedEdges);
			done = false;
			uf.unite(i, j);
			newExpectedCost += dijk.dists[j];
			paths.emplace_back();
			int p = j;
			while (p != i) {
				int np = dijk.prev[p];
				paths.back().emplace_back(p, np);
				usedEdges.emplace(min(p, np), max(p, np));
				p = np;
			}
		}
		return paths;
	}


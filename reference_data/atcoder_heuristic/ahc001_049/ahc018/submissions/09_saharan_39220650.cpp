class MeshGen {
private:
	double radius = {};
	double maxDistFromFixed = {};

public:
	vector<int2> fixed;
	Mesh generated;

	MeshGen() {
	}

	void clear() {
		fixed.clear();
		generated.clear();
	}

	void generate(double radius, double maxDistFromFixed) {
		this->radius = radius;
		this->maxDistFromFixed = maxDistFromFixed;
		trace("generating mesh...");
		solve();
	}

	void beginMovie() {
		mov.clear();
		gr.screen(N, N);
	}

	void endMovie() {
		writeMovie(mov, "debug.html");
	}

	void addFrame() {
		gr.clear();
		for (auto& v : vs) {
			double x = v.j;
			double y = v.i;
			bool fixed = v.invM == 0;
			gr.noStroke();
			if (fixed)
				gr.fill(1, 0, 0);
			else
				gr.fill(0, 0, 0);
			gr.circle(x, y, 1);
		}
		mov.addFrame(gr);
	}

private:
	vector<Vert> vs;
	vector<pii> ns;

	void solve() {
		vs.clear();
		for (auto p : fixed) {
			vs.emplace_back(p.i, p.j, true);
		}
		double interval = sqrt(sqrt(3) / 2) * radius * 0.9;
		int num = (int) round(N / interval) + 1;
		interval = (double) N / (num - 1);
		rep0(i, num) {
			double fi = i * interval;
			rep0(j, num) {
				double fj = j * interval;
				vs.emplace_back(fi, fj, false);
			}
		}
		int st = timer();
		constexpr int ITER1 = 4;
		constexpr int ITER2 = 50;
		rep0(i1, ITER1) {
			bool last = i1 == ITER1 - 1;
			contain(true);
			updateNeighbors();
			rep0(i2, ITER2) {
				collide((double) i1 / ITER1);
				if (last)
					contain(false);
			}
		}
		contain(true);
		updateNeighbors();
		int en = timer();
		trace("mesh generation time: ", en - st);

		generated.clear();
		int index = 0;
		for (auto& v : vs) {
			generated.vs.emplace_back(index++, (int) v.i, (int) v.j, v.invM == 0);
		}
		for (auto n : ns) {
			auto& v1 = generated.vs[n.first];
			auto& v2 = generated.vs[n.second];
			double di = v1.i - v2.i;
			double dj = v1.j - v2.j;
			if (sqrt(di * di + dj * dj) < radius * 1.4) {
				generated.vs[n.first].ns.push_back(n.second);
				generated.vs[n.second].ns.push_back(n.first);
			}
		}
	}

	void contain(bool remove) {
		constexpr double MIN = 0.5;
		constexpr double MAX = N - 0.5;
		double mergin = radius * 0.5;
		for (auto& v : vs) {
			if (v.i < MIN && v.i > MIN - mergin) {
				v.i = MIN;
			}
			if (v.j < MIN && v.j > MIN - mergin) {
				v.j = MIN;
			}
			if (v.i > MAX && v.i < MAX + mergin) {
				v.i = MAX;
			}
			if (v.j > MAX && v.j < MAX + mergin) {
				v.j = MAX;
			}
		}
		if (remove) {
			vs.erase(remove_if(vs.begin(), vs.end(),
			             [&](const Vert& v) {
				             bool rem = v.i < MIN || v.j < MIN || v.i > MAX || v.j > MAX;
				             if (!rem) {
					             rem = true;
					             for (auto& f : fixed) {
						             int di = v.i - f.i;
						             int dj = v.j - f.j;
						             if (di * di + dj * dj < maxDistFromFixed * maxDistFromFixed)
							             rem = false;
					             }
				             }
				             return rem;
			             }),
			    vs.cend());
		}
	}

	void collide(double t) {
		for (auto n : ns) {
			int i = n.first;
			int j = n.second;
			auto& v1 = vs[i];
			auto& v2 = vs[j];
			double di = v1.i - v2.i;
			double dj = v1.j - v2.j;
			double d2 = di * di + dj * dj;
			if (d2 == 0) {
				di = 0.01;
				d2 = 0.01;
			}
			double d = sqrt(d2);
			double invD = 1 / d;
			double ni = di * invD;
			double nj = dj * invD;
			double overlap = radius - d;
			overlap = max(overlap, -radius * 0.05);
			double mass = 1 / (v1.invM + v2.invM);
			double k = 0.9 - t * 0.5;
			double p = mass * overlap * k;
			double fi = p * ni;
			double fj = p * nj;
			v1.i += fi * v1.invM;
			v1.j += fj * v1.invM;
			v2.i -= fi * v2.invM;
			v2.j -= fj * v2.invM;
		}
	}

	void updateNeighbors() {
		ns.clear();
		int n = len(vs);
		double hit = radius * 1.6;
		double r2 = hit * hit;
		rep0(i, n) {
			rep0(j, i) {
				auto& v1 = vs[i];
				auto& v2 = vs[j];
				if (v1.invM == 0 && v2.invM == 0)
					continue;
				double di = v1.i - v2.i;
				double dj = v1.j - v2.j;
				if (di * di + dj * dj < r2) {
					ns.emplace_back(i, j);
				}
			}
		}
	}
};


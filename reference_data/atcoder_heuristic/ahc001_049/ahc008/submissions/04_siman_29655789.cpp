  int search_next_team_target(int tid) {
    Team &team = g_teams[tid];
    int next_pid = NOT_FOUND;
    double min_dist = INT_MAX;
    int member_num = team.ids.size();
    Hunter &hunter = g_hunters[0];
    vector<int> hunter_ids = team.ids;
    sort(hunter_ids.begin(), hunter_ids.end(), comp);
    int min_x = H;
    int max_x = 0;
    for (int id : team.ids) {
      min_x = min(min_x, g_hunters[id].x);
      max_x = max(max_x, g_hunters[id].x);
    }

    for (int pid = 0; pid < petNum; ++pid) {
      Pet &pet = g_pets[pid];
      if (g_distance[hunter.x][hunter.y][pet.x][pet.y] == UNREACHABLE) continue;

      int max_d = 0;
      double total_dist = 0;
      for (int id : team.ids) {
        double dist = abs(pet.y - g_hunters[id].y);
        max_d = max(max_d, (int) dist);
        if (team.ids.size() <= 3) {
          dist += 0.5 * abs(pet.x - g_hunters[id].x);
        }
        total_dist += dist;
      }
      if (hunterNum == 6) {
        if (tid == 0) {
          total_dist += pet.y;
        } else if (tid == g_teams.size() - 1) {
          total_dist += W - pet.y;
        }
      }
      if (team.ids.size() <= 3) {
        int md = INT_MAX;
        for (int i = 0; i < team.ids.size() - 1; ++i) {
          int id = hunter_ids[i];
          int nid = hunter_ids[i + 1];
          int mx = (g_hunters[id].x + g_hunters[nid].x) / 2;
          md = min(md, abs(mx - pet.x));
        }
        total_dist += pow(md, 2);
      }
      if (hunterNum != 5 || is_all_line_completed()) {
        if (pet.targeted_tid != NOT_FOUND) total_dist += 9999;
      }
      if (hunterNum == 5) {
        if (g_room_id[pet.x][pet.y] != UNDEFINED) total_dist -= 3;
        if (g_room_id[pet.x][pet.y] != UNDEFINED && pet.type == COW) total_dist -= 10;
      } else {
        if (g_room_id[pet.x][pet.y] != UNDEFINED) total_dist -= 3;
        if (g_room_id[pet.x][pet.y] == UNDEFINED && pet.type == COW) total_dist += 10;
        if (g_room_id[pet.x][pet.y] != UNDEFINED && pet.type == COW) total_dist -= 10;
      }
      if (pet.y < g_min_y) total_dist += 9999;
      bool in_room = true;

      for (int direct = 0; direct < 4; ++direct) {
        int nx = pet.x + DX[direct];
        int ny = pet.y + DY[direct];
        int rx = pet.x + DX[(direct + 2) % 4];
        int ry = pet.y + DY[(direct + 2) % 4];
        if (GRID_PATTERN[nx][ny] == FENCE && GRID_PATTERN[rx][ry] == FENCE) {
          total_dist -= 3;
          in_room = false;
        }
      }

      if (g_room_id[pet.x][pet.y] != UNDEFINED && in_room && (pet.type != DOG && pet.type != CAT)) {
        total_dist -= 5;
      }

      for (int i = 0; i < team.ids.size() - 1; ++i) {
        int id = hunter_ids[i];
        int nid = hunter_ids[i + 1];
        Hunter &h1 = g_hunters[id];
        Hunter &h2 = g_hunters[nid];

        if (h1.x <= pet.x && pet.x <= h2.x) {
          // total_dist -= (max_d <= 2 && g_room_id[pet.x][pet.y] != UNDEFINED) ? 5 : 1;
        } else if (h1.hid == 0 && pet.x <= h1.x) {
          total_dist -= (max_d <= 2 && g_room_id[pet.x][pet.y] != UNDEFINED) ? 3 : 1;
        } else if (h2.hid == H_CNT - 1 && h2.x <= pet.x) {
          total_dist -= (max_d <= 2 && g_room_id[pet.x][pet.y] != UNDEFINED) ? 3 : 1;
        }
      }

      if ((pet.type == CAT || pet.type == DOG) && GRID_PATTERN[pet.x][pet.y] == DOOR) {
        int px = pet.x + DX[pet.next_dir];
        int py = pet.y + DY[pet.next_dir];
        if (g_room_id[px][py] != UNDEFINED) {
          total_dist -= 1;
        }
      }

      if (min_dist > total_dist) {
        min_dist = total_dist;
        next_pid = pid;
      }
    }

    return next_pid;
  }


struct Team {
  int id;
  int target_pid;
  vector<int> ids;
  set<int> tasks;

  Team() {
    this->ids.clear();
    this->target_pid = NOT_FOUND;
    this->tasks.clear();
  }

  void reshuffle_hid() {
    vector<int> hid_list;
    vector<int> order;
    for (int i = 0; i < ids.size(); ++i) {
      int id = ids[i];
      hid_list.push_back(g_hunters[id].hid);
      order.push_back(i);
    }

    sort(hid_list.begin(), hid_list.end());
    int min_dist = INT_MAX;
    vector<int> best_list = hid_list;
    do {
      int total_dist = 0;
      for (int i = 0; i < ids.size(); ++i) {
        int id = ids[i];
        Hunter &hunter = g_hunters[id];

        int hid = hid_list[i];
        int vx = H_LINES[hid];

        if (target_pid != NOT_FOUND) {
          Pet &pet = g_pets[target_pid];
          total_dist = max(total_dist, 5 * abs(hunter.x - vx) + abs(hunter.y - pet.y));
        } else {
          total_dist = max(total_dist, 5 * abs(hunter.x - vx));
        }
      }
      if (min_dist > total_dist) {
        min_dist = total_dist;
        best_list = hid_list;
      }
    } while (next_permutation(hid_list.begin(), hid_list.end()));

    for (int i = 0; i < ids.size(); ++i) {
      int id = ids[i];
      g_hunters[id].hid = best_list[i];
    }
  }
};


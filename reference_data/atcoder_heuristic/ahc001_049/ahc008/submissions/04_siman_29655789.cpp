      for (int direct = 0; direct < 4; ++direct) {
        int nx = hunter.x + DX[direct];
        int ny = hunter.y + DY[direct];
        if (GRID_PATTERN[nx][ny] != DOOR) continue;
        if (g_exist_fence[nx][ny]) continue;

        g_blocked_door[nx][ny] = true;
      }

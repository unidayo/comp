int char2dir(char ch) {
  if (ch == MOVE_CMD[UP]) {
    return UP;
  } else if (ch == MOVE_CMD[RIGHT]) {
    return RIGHT;
  } else if (ch == MOVE_CMD[DOWN]) {
    return DOWN;
  } else if (ch == MOVE_CMD[LEFT]) {
    return LEFT;
  } else {
    fprintf(stderr, "Unexpected dir: %c\n", ch);
    assert(false);
  }
}

bool is_build_action(char cmd) {
  if (STAY_CMD == cmd) return false;
  if (MOVE_CMD[UP] == cmd) return false;
  if (MOVE_CMD[RIGHT] == cmd) return false;
  if (MOVE_CMD[DOWN] == cmd) return false;
  if (MOVE_CMD[LEFT] == cmd) return false;

  return true;
}


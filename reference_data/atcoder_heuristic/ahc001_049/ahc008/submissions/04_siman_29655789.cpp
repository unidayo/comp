    vector<int> best_list = vid_list;

    do {
      int total_dist = 0;
      bool ok = true;
      for (int id = 0; id < hunterNum; ++id) {
        Hunter &hunter = g_hunters[id];
        int vid = vid_list[id];
        Team &team = g_teams[hunter.tid];
        int vy = V_LINES[vid];
        int dist = min(g_distance[hunter.x][hunter.y][1][vy], g_distance[hunter.x][hunter.y][H][vy]);
        if (not team.tasks.count(vid)) ok = false;
        if (hunterNum == 7 && team.id == 0 && vid == 0) {
          ok = false;
        }
        if (hunterNum == 6 && team.id == 0 && vid <= 1) {
          ok = false;
        }
        if (hunterNum == 5 && team.id == 0 && vid <= 2) {
          ok = false;
        }
        total_dist += dist;
      }
      if (min_dist > total_dist && ok) {
        min_dist = total_dist;
        best_list = vid_list;
      }
    } while (next_permutation(vid_list.begin(), vid_list.end()));

